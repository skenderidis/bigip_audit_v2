import { CHECK_KEYS } from './auditChecks'

// Build an F5 declarative WAF policy (v17.1) from a template's checks. Each
// check key is an F5 blocking-settings violation name, so it maps 1:1: an
// enabled check becomes a violation with alarm+block on, disabled stays off.
export function buildAsmPolicy(name, checks) {
  const on = (k) => checks[k] === 'yes'
  return {
    policy: {
      name: name || 'guided-policy',
      description: 'Generated by the ADSP guided configuration wizard.',
      template: { name: 'POLICY_TEMPLATE_FUNDAMENTAL' },
      applicationLanguage: 'utf-8',
      enforcementMode: 'blocking',
      'signature-settings': {
        minimumAccuracyForAutoAddedSignatures: 'medium',
        placeSignaturesInStaging: true,
        signatureStaging: true,
      },
      // Policy Builder learning: cookies stay selective; file types and URLs
      // learn new entities only when the matching allow-list check is enabled;
      // parameters learn all when the Illegal parameter check is enabled,
      // otherwise selective.
      'policy-builder': {
        learnExplicitCookies: 'selective',
        learnExplicitFiletypes: on('VIOL_FILETYPE') ? 'always' : 'never',
        learnExplicitUrls: on('VIOL_URL') ? 'always' : 'never',
        learnExplicitParameters: on('VIOL_PARAMETER') ? 'always' : 'selective',
      },
      'blocking-settings': {
        violations: CHECK_KEYS.map(k => ({ name: k, alarm: on(k), block: on(k) })),
      },
    },
  }
}

// Safe filename from the template name, falling back to a default.
export function policyFileName(name) {
  const base = (name || 'guided-policy').trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
  return `${base || 'guided-policy'}.json`
}

// Build the policy and trigger a browser download.
export function downloadAsmPolicy(name, checks) {
  const obj = buildAsmPolicy(name, checks)
  const blob = new Blob([JSON.stringify(obj, null, 2)], { type: 'application/json' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = policyFileName(name)
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
}
